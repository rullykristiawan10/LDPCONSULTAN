-- 1. Table: articles (Untuk Blog & Publikasi Teknik)
CREATE TABLE IF NOT EXISTS public.articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    category TEXT NOT NULL DEFAULT 'Engineering',
    summary TEXT,
    featured BOOLEAN DEFAULT FALSE,
    image TEXT DEFAULT '/images/office_presentation.jpg',
    author JSONB DEFAULT '{"name": "Tim Ahli LDP", "role": "Consultant Engineer", "avatar": "/images/avatar_ade.jpg"}'::jsonb,
    published_at TEXT,
    read_time TEXT DEFAULT '5 menit',
    views BIGINT DEFAULT 0,
    tags JSONB DEFAULT '[]'::jsonb,
    content TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable RLS on articles
ALTER TABLE public.articles ENABLE ROW LEVEL SECURITY;

-- Allow public read access to articles
CREATE POLICY "Public articles are viewable by everyone" 
ON public.articles FOR SELECT 
USING (true);

-- Allow insert/update/delete for authenticated or with anon key for admin dashboard
CREATE POLICY "Enable insert for anon/service" 
ON public.articles FOR INSERT 
WITH CHECK (true);

CREATE POLICY "Enable update for anon/service" 
ON public.articles FOR UPDATE 
USING (true);

CREATE POLICY "Enable delete for anon/service" 
ON public.articles FOR DELETE 
USING (true);


-- 2. Table: consultations (Untuk Permintaan Konsultasi & Lead Client)
CREATE TABLE IF NOT EXISTS public.consultations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    company TEXT,
    email TEXT NOT NULL,
    phone TEXT,
    service_type TEXT,
    message TEXT,
    status TEXT DEFAULT 'new', -- 'new', 'in_review', 'contacted', 'closed'
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable RLS on consultations
ALTER TABLE public.consultations ENABLE ROW LEVEL SECURITY;

-- Allow anyone to insert a consultation inquiry
CREATE POLICY "Anyone can submit consultation inquiry" 
ON public.consultations FOR INSERT 
WITH CHECK (true);

-- Allow reading consultations for dashboard
CREATE POLICY "Dashboard can view consultations" 
ON public.consultations FOR SELECT 
USING (true);

CREATE POLICY "Dashboard can update consultations" 
ON public.consultations FOR UPDATE 
USING (true);


